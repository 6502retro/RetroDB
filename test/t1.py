# MouseDB: forms, records, validation, saving and loading
import sys; sys.path.insert(0, 'test')
from common import *
V = 'test/v1'; fresh(V)
F = [('Name', 'Text', 30, 1), ('Qty', 'Number', 0, 1), ('Price', 'Money', 0, 1),
     ('When', 'Date', 0, 1), ('OK', 'Yes/No', 0, 1)]
a = start(V)
check('empty start shows the no-form message', 'This database has no form yet.' in a.plain())
check('menu bar says Untitled', 'Database: Untitled' in rows(a, 0, 1))
a.key('N', oa=True); a.run()
check('New Record with no form opens Design Form', 'Design Form' in a.plain())
design(a, F)
check('form made: headings', 'Name' in rows(a, 2, 3) and 'Price' in rows(a, 2, 3) and 'OK' in rows(a, 2, 3))
check('status: 0 of 250 records', '0 of 250 records' in rows(a, 22, 23))
check('status: Modified after designing', 'Modified' in rows(a, 22, 23))
# validation
a.key('N', oa=True); a.run(); a.key('Widget\t1-2\r'); a.run()
check('bad whole number refused', 'Please type a whole number in' in a.plain() and 'Qty' in a.plain())
a.key('\r'); a.run()
a.key(0x18); a.key('7\t99999999\r'); a.run()
check('money over $9,999,999.99 refused', 'is too large' in a.plain() and '$9,999,999.99' in a.plain())
a.key('\r'); a.run(); a.key(0x18); a.key('1,234.5\t13/40/2020\r'); a.run()
check('bad date refused', 'Please type a date in' in a.plain())
a.key('\r'); a.run(); a.key(0x18); a.key('3/5/1984\t\r'); a.run()
check('record added', 'Widget' in rows(a, 4, 5))
r = rows(a, 4, 5)
check('row shows number, money, ISO date: ' + r.strip(), '7' in r and '$1234.50' in r and '1984-03-05' in r)
a.key('N', oa=True); a.run(); a.key('\r'); a.run()
check('empty record refused', 'Please fill in at least one field' in a.plain())
a.key('\r'); a.run(); a.key(0x1B); a.run()
newrec(a, ['Gadget', '-5', '-0.5', '2001-1-2', 'Y'])
newrec(a, ['Gizmo', '1,000', '$3', '1999', 'N'])
newrec(a, ['', '0', '0', '12/1999', ''])
L = listrows(a, 5)
check('negative number and money shown: ' + L[1], '-5' in L[1] and '-$0.50' in L[1])
check('date 2001-1-2 becomes 2001-01-02', '2001-01-02' in L[1])
check('Yes/No shown', 'Yes' in L[1] and 'No' in L[2])
check('number with comma: 1000', '1000' in L[2])
check('MM/YYYY date becomes 1999-12', '1999-12' in L[3])
check('zero is shown as 0 and $0.00', ' 0' in L[3] and '$0.00' in L[3])
check('status total Price: $1236.00', 'Total Price: $1237.00' in rows(a, 22, 23))
# save
a.key('S', oa=True); a.run()
check('Save of an untitled database asks for a name', 'Save this database under a new' in a.plain())
a.key('1BAD\r'); a.run()
check('bad name refused', 'A ProDOS name starts with a letter' in a.plain())
a.key('\r'); a.run(); a.key(0x18); a.key('STOCK\r'); a.run()
check('saved: menu bar says STOCK', 'Database: STOCK' in rows(a, 0, 1) and 'Modified' not in rows(a, 22, 23))
L = lines(V, 'STOCK')
check('file header', L[0] == 'MOUSEDB1' and L[1] == '5' and L[2] == '"Name",1,30,1' and L[3] == '"Qty",2,10,1')
check('file kinds', L[4] == '"Price",3,12,1' and L[5] == '"When",4,10,1' and L[6] == '"OK",5,3,1')
check('file count', L[7] == '4')
check('file record 1', L[8:13] == ['"Widget"', '"7"', '"1234.50"', '"1984-03-05"', '""'])
check('file record 2', L[13:18] == ['"Gadget"', '"-5"', '"-0.50"', '"2001-01-02"', '"Yes"'])
check('file record 4 (blank name, zero)', L[23:28] == ['""', '"0"', '"0.00"', '"1999-12"', '""'])
check('MOUSEDB.LAST names STOCK', lines(V, 'MOUSEDB.LAST')[0] == 'STOCK')
check('no MOUSEDB.SAVING left', not os.path.exists(V + '/MOUSEDB.SAVING'))
# load it back
a = start(V)
check('reopened at start: STOCK', 'Database: STOCK' in rows(a, 0, 1))
check('reopened: 4 records', '4 of 250 records' in rows(a, 22, 23))
check('reopened: same rows', listrows(a, 4) == L4 if (L4 := listrows(a, 4)) else False)
a.key('\r'); a.run()
p = a.plain()
check('edit window shows the values as typed text', '1234.50' in p and '1984-03-05' in p and 'Widget' in p)
check('edit window: Record 1 of 4', 'Record 1 of 4' in p)
a.key(0x1B); a.run()
# duplicate and delete
a.key(0x0A); a.key('C', oa=True); a.run()
check('Duplicate opens a copy', 'Duplicate Record' in a.plain() and 'Gadget' in a.plain())
a.key(0x18); a.key('Gadget II\r'); a.run()
check('duplicate added at the end', 'Gadget II' in listrows(a)[4] and '5 of 250' in rows(a, 22, 23))
a.key('D', oa=True); a.run()
check('delete asks, naming the record', 'Delete this record?' in a.plain() and 'Gadget II' in a.plain())
a.key('\r'); a.run()
check('deleted', '4 of 250' in rows(a, 22, 23) and 'Gadget II' not in a.plain())
# revert
a.key('N', oa=True); a.run(); a.key('Temp\r'); a.run()
menu(a, 1, 4)
check('Revert asks', 'Discard your changes and reload' in a.plain())
a.key('\r'); a.run()
check('reverted to 4 saved records', '4 of 250' in rows(a, 22, 23) and 'Temp' not in a.plain())
# quit with changes
a.key('N', oa=True); a.run(); a.key('Temp\r'); a.run()
a.key('Q', oa=True); a.run()
check('quit with changes asks to save', 'Save changes to STOCK' in a.plain())
a.key(0x1B); a.run()
check('Cancel stays', not a.quit)
a.key('Q', oa=True); a.run(); a.key('D'); a.run()
check("Don't Save quits", a.quit)
check('file unchanged by quitting without saving', lines(V, 'STOCK')[7] == '4')
done()
